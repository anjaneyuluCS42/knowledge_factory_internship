class Country:

    def __init__(
        self,
        name,
        capital,
        currency,
        population,
        flag,
        languages,
        region,
        subregion,
        timezone,
        maps
    ):

        self.name = name
        self.capital = capital
        self.currency = currency
        self.population = population
        self.flag = flag
        self.languages = languages
        self.region = region
        self.subregion = subregion
        self.timezone = timezone
        self.maps = maps